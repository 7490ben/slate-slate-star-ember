export function mergeAccount(
  base: Account,
  live?: Partial<Account> | null,
): Account {
  if (!live) return base;
  return {
    ...base,
    name: live.name ?? base.name,
    bio: live.bio ?? base.bio,
    followers: live.followers ?? base.followers,
    following: live.following ?? base.following,
    tweets: live.tweets ?? base.tweets,
    verified: live.verified ?? base.verified,
    verifyType: live.verifyType ?? base.verifyType,
  };
}

export function mergePosts(base: Post[], liveLikes?: Record<string, number>): Post[] {
  if (!liveLikes) return base;
  return base
    .map((p) =>
      liveLikes[p.id] != null ? { ...p, likes: liveLikes[p.id]! } : p,
    )
    .filter((p) => p.likes >= BANG_FLOOR)
    .sort((a, b) => b.likes - a.likes);
}
