export function affiliateLabels(account: Account): string[] {
  const labels = [account.affiliate, ...(account.affiliates ?? [])].filter(
    (v): v is string => Boolean(v),
  );
  return [...new Set(labels)];
}

export function accountByHandle(handle: string): Account | undefined {
  const key = handle.toLowerCase();
  return (
    ACCOUNTS.find((a) => a.handle.toLowerCase() === key) ??
    TEAM.find((a) => a.handle.toLowerCase() === key)
  );
}

export const GIF_PAGES = new Set(["gifshitpost", "gifooc"]);
const CARD_SKIP = new Set(["2052519077701406832"]);
